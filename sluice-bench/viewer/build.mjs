#!/usr/bin/env node
// node viewer/build.mjs [item]   (run from ~/sluice-bench)
// Builds viewer/data.js for index.html from <item>/codes.json (code -> "<run>/<still>.png"). Each run gets one random
// letter, the same on every title; the letter -> run key goes to <item>/_blind/letters-key.json, which the viewer never
// loads. data.js holds only titles, letters, codes and image paths: no run or arm names.
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'

const item = process.argv[2] ?? 'F2'
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const codes = JSON.parse(fs.readFileSync(path.join(root, item, 'codes.json'), 'utf8'))
const keyFile = path.join(root, item, '_blind', 'letters-key.json')
const runs = [...new Set(Object.values(codes).map((v) => v.split('/')[0]))]
let key = fs.existsSync(keyFile) ? JSON.parse(fs.readFileSync(keyFile, 'utf8')) : null // keep letters stable on a rebuild
if (!key || runs.some((r) => !Object.values(key).includes(r))) {
  const letters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.slice(0, runs.length).split('')
  const shuffled = [...runs].sort(() => crypto.randomInt(3) - 1).sort(() => crypto.randomInt(3) - 1)
  for (let i = shuffled.length - 1; i > 0; i--) { const j = crypto.randomInt(i + 1); [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]] }
  key = Object.fromEntries(letters.map((l, i) => [l, shuffled[i]]))
  fs.writeFileSync(keyFile, JSON.stringify(key, null, 2) + '\n')
}
const letterOf = Object.fromEntries(Object.entries(key).map(([l, r]) => [r, l]))
const titles = {}
for (const [code, rel] of Object.entries(codes)) {
  const [run, file] = rel.split('/')
  const title = file.replace(/\.png$/, '')
  ;(titles[title] ??= []).push({ letter: letterOf[run], code, src: `${item}/_blind/${code}.png` })
}
const order = Object.keys(titles).sort((a, b) => {
  const [sa, na] = a.split('-'), [sb, nb] = b.split('-')
  return na === nb ? (sa < sb ? 1 : -1) : Number(na) - Number(nb) // by moment, then 1440x900 before 1024x640
})
const data = { item, titles: order.map((t) => ({ title: t, stills: titles[t].sort((a, b) => a.letter.localeCompare(b.letter)) })) }
fs.writeFileSync(path.join(root, 'viewer', 'data.js'), `// Generated by viewer/build.mjs: titles, blind letters, codes and image paths only.\nwindow.STILLS = ${JSON.stringify(data, null, 2)};\n`)
console.log(`${order.length} titles, ${runs.length} letters, ${Object.keys(codes).length} stills -> viewer/data.js`)
