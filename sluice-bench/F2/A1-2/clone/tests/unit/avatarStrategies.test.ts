// 04 §7: pictures by several routes, in the order an org has taught us. Stub routes here; the last
// test runs the real strategies against the fake org (Graph on its identity host). Invented bytes only.
import { describe, expect, it } from 'vitest';
import orbitWeek from '@fixtures/scenarios/orbit-week';
import { FAKE_ORG_URL } from '@fixtures/ado';
import { FIXTURE_ORG, guidFromName } from '@fixtures/dsl';
import type { AdoResponse } from '@shared/contracts/transport';
import { isAvatarImage } from '@shared/scene/avatar';
import { allowlist, vsspsBaseOf } from '../../src/main/ado/http';
import { Cache } from '../../src/main/db/cache';
import {
  DENIED_TTL_MS, descriptorOf, fetchPictures, resetPictureMemory, sniff, strategyOrder, type PictureClient, type PicturePort, type Who,
} from '../../src/main/avatars/strategies';
import { harness } from '../golden/ingest';

const ORG = 'https://dev.azure.com/contoso';
const KEY = 'org-1';
const PNG = Uint8Array.from(Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR4nGP4z8DwHwAFAAH/q842iQAAAABJRU5ErkJggg==', 'base64'));
const b64 = Buffer.from(PNG).toString('base64');

const bytes = (): AdoResponse => ({ status: 200, headers: { 'content-type': 'image/png' }, body: PNG });
const json = (body: unknown): AdoResponse => ({ status: 200, headers: {}, body });
const status = (n: number): AdoResponse => ({ status: n, headers: {}, body: null });

const who = (n: number): Who => ({ id: `id-${n}`, imageUrl: `${ORG}/_apis/GraphProfile/MemberAvatars/aad.p${n}` });
const people = (n: number) => Array.from({ length: n }, (_, i) => who(i));

/** Which route a URL is. */
const route = (url: string) => (url.includes('vssps.dev.azure.com') ? 'graph' : url.includes('identityImage') ? 'web' : 'member');

function setup(answers: Partial<Record<'member' | 'graph' | 'web', (url: string) => AdoResponse>>) {
  const settings = new Map<string, unknown>();
  const avatars = new Map<string, string | null>();
  const calls: string[] = [];
  const port: PicturePort = {
    setting: <T,>(k: string) => (settings.has(k) ? (JSON.parse(JSON.stringify(settings.get(k))) as T) : null),
    setSetting: (k, v) => { settings.set(k, JSON.parse(JSON.stringify(v))); },
    setAvatar: (_o, id, u) => { avatars.set(id, u); },
    clearMissedAvatars: () => { for (const [k, v] of avatars) if (v === null) avatars.delete(k); },
  };
  const client: PictureClient = {
    org: ORG,
    avatarRaw: async (url) => { const r = route(url); calls.push(r); return (answers[r] ?? (() => status(404)))(url); },
  };
  const run = (who: Who[], now = 1_000_000) => fetchPictures({ client, cache: port, org: KEY, who, now });
  return { settings, avatars, calls, port, client, run };
}

describe('the identity host (04 §1)', () => {
  it('is the org’s own vssps host, and only for the transport', () => {
    expect(vsspsBaseOf('https://dev.azure.com/contoso')).toBe('https://vssps.dev.azure.com/contoso');
    expect(vsspsBaseOf('https://contoso.visualstudio.com')).toBe('https://contoso.vssps.visualstudio.com');
    expect(vsspsBaseOf('https://tfs.example.com/tfs/col')).toBeNull();
    const ok = allowlist(ORG);
    expect(ok('https://vssps.dev.azure.com/contoso/_apis/graph/Subjects/aad.x/avatars')).toBe(true);
    expect(ok('https://vssps.dev.azure.com/other/_apis/graph/Subjects/aad.x/avatars')).toBe(false);
    expect(ok('https://vssps.dev.azure.com/contoso-evil/_apis/graph')).toBe(false);
    expect(ok('https://app.vssps.visualstudio.com/contoso/_apis')).toBe(false);
    expect(allowlist(ORG, false)('https://vssps.dev.azure.com/contoso/_apis/graph')).toBe(false); // opening pages stays on the org
  });
  it('reads a descriptor out of the picture link, and a picture’s type out of its bytes', () => {
    expect(descriptorOf(`${ORG}/_apis/GraphProfile/MemberAvatars/aad.abc123`)).toBe('aad.abc123');
    expect(descriptorOf(`${ORG}/_apis/GraphProfile/MemberAvatars/aad.abc123?size=2`)).toBe('aad.abc123');
    expect(descriptorOf(`${ORG}/_api/_common/identityImage?id=1`)).toBeNull();
    expect(sniff(PNG)).toBe('image/png');
    expect(sniff(Uint8Array.from([0xff, 0xd8, 0xff]))).toBe('image/jpeg');
    expect(sniff(Uint8Array.from([1, 2, 3]))).toBeNull();
  });
});

describe('picture strategies (04 §7)', () => {
  it('starts with the identity link, and keeps it when it works', async () => {
    const t = setup({ member: bytes });
    await t.run(people(3));
    expect(t.calls).toEqual(['member', 'member', 'member']);
    expect([...t.avatars.values()].every((u) => isAvatarImage(u!))).toBe(true);
  });

  it('falls back when the token is refused, sets the refused route aside, and starts with the one that worked next time', async () => {
    const t = setup({ member: () => status(401), graph: () => json({ value: b64, isAutoGenerated: false }) });
    await t.run(people(6));
    // Every person got a picture; member was tried only until it was set aside (two refusals, four in flight at most).
    expect([...t.avatars.values()].every((u) => u !== null && isAvatarImage(u))).toBe(true);
    expect(t.avatars.size).toBe(6);
    expect(t.calls.filter((c) => c === 'member').length).toBeLessThanOrEqual(4);
    expect(t.calls.filter((c) => c === 'web')).toEqual([]);
    expect(t.settings.get(`avatars:${KEY}`)).toMatchObject({ preferred: 'graph', denied: { member: 1_000_000 } });

    t.calls.length = 0;
    t.avatars.clear();
    await t.run(people(6), 1_000_000 + 60_000); // a later sync: Graph first, member skipped
    expect(t.calls).toEqual(Array(6).fill('graph'));
    expect(t.avatars.size).toBe(6);
  });

  it('tries a set-aside route again after a day', () => {
    const mem = { preferred: 'graph' as const, denied: { member: 5 } };
    expect(strategyOrder(mem, 5 + DENIED_TTL_MS - 1)).toEqual(['graph', 'web']);
    expect(strategyOrder(mem, 5 + DENIED_TTL_MS)).toEqual(['graph', 'member', 'web']);
  });

  it('keeps people unasked when every route is refused, so a better token finds them', async () => {
    const t = setup({ member: () => status(401), graph: () => status(401), web: () => status(401) });
    await t.run(people(4));
    expect(t.avatars.size).toBe(0); // not stored as "none"
    expect(t.settings.get(`avatars:${KEY}`)).toMatchObject({ denied: { member: 1_000_000, graph: 1_000_000, web: 1_000_000 } });
    t.calls.length = 0;
    await t.run(people(4), 1_000_000 + 1000);
    expect(t.calls).toEqual([]); // while the refusals stand, asking costs nothing
  });

  it('believes a route that has not been refusing us when it says someone has no picture', async () => {
    const t = setup({ member: (u) => (u.endsWith('aad.p1') ? status(404) : bytes()) });
    await t.run(people(2));
    expect(t.avatars.get('id-1')).toBeNull(); // asked, none: stored as ''
    expect(t.calls).toEqual(['member', 'member']); // and no other route was wasted on it
  });

  it('asks the other routes when a route that has been refusing us says 404', async () => {
    // Member refuses most people (401) and 404s one: that 404 is no proof, so Graph is asked.
    const t = setup({ member: (u) => (u.endsWith('aad.p2') ? status(404) : status(401)), graph: () => json({ value: b64 }) });
    await t.run(people(3));
    expect(t.avatars.size).toBe(3);
    expect([...t.avatars.values()].every((u) => u !== null && isAvatarImage(u))).toBe(true);
  });

  it('counts an ADO-drawn initials picture, and a sign-in page, as no picture', async () => {
    const t = setup({ member: () => ({ status: 200, headers: { 'content-type': 'text/html' }, body: Uint8Array.from([60]) }), graph: () => json({ value: b64, isAutoGenerated: true }), web: () => status(404) });
    await t.run([who(0)]);
    expect(t.avatars.get('id-0')).toBeNull();
  });

  it('leaves a person for later when the only answers were failures', async () => {
    const t = setup({ member: () => status(500), graph: () => status(500), web: () => status(500) });
    await t.run([who(0)]);
    expect(t.avatars.has('id-0')).toBe(false);
  });

  it('forgets refusals and misses on reconnect', async () => {
    const t = setup({ member: () => status(401), graph: () => status(404), web: () => status(404) });
    await t.run(people(3));
    expect(t.avatars.size).toBe(3);
    resetPictureMemory(t.port, KEY);
    expect(t.avatars.size).toBe(0);
    expect(t.settings.get(`avatars:${KEY}`)).toMatchObject({ denied: {} });
  });
});

describe('picture strategies against the fake org', () => {
  it('reaches Graph on the identity host when the identity link is refused', async () => {
    const h = await harness(orbitWeek, Cache.open(':memory:'), { avatarDenied: ['member'] });
    const id = guidFromName('person', 'mina');
    h.cache.putIdentity(FIXTURE_ORG, { id, displayName: 'Mina Sato', imageUrl: `${FAKE_ORG_URL}/_apis/GraphProfile/MemberAvatars/fx.${id}` }, h.clock());
    await fetchPictures({ client: h.client, cache: h.cache, org: FIXTURE_ORG, who: h.cache.identitiesNeedingAvatar(FIXTURE_ORG), now: h.clock() });
    expect(isAvatarImage(h.cache.identities(FIXTURE_ORG).get(id)!.avatar!)).toBe(true);
  });
});
