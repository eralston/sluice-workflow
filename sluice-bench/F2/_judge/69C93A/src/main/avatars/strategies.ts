// 04 §7 — profile pictures. ADO has more than one way to hand over a person's picture, and which
// ones a token may use differs by org and by PAT scope: the identity's own `imageUrl` (a
// GraphProfile call), the Graph avatar API (scope `vso.graph`, on the org's identity host), and the web
// app's identity image. Each is a strategy. For an org the order is learned: the one that last worked
// goes first, a strategy the token is refused on is skipped for a day, and the rest follow. A picture
// is a nice-to-have, so nothing here ever fails a sync. Pure of Electron; the client is a port.
import type { AdoResponse } from '@shared/contracts/transport';
import type { Guid, OrgKey } from '@shared/contracts/keys';
import { devlog } from '../devlog';
import { vsspsBaseOf } from '../ado/http';
import type { Version } from '../ado/client';

export type StrategyId = 'member' | 'graph' | 'web';
/** Where an org with no history starts: the link ADO gave us, then Graph, then the web app's route. */
export const DEFAULT_ORDER: readonly StrategyId[] = ['member', 'graph', 'web'];
/** The most a kept picture may be (it rides in an inline data URL). */
export const MAX_BYTES = 140_000;
/** A strategy the token was refused on is not tried again for this long (a fixed scope is picked up on reconnect, sooner). */
export const DENIED_TTL_MS = 24 * 3_600_000;
/** Refusals in one run, with no success, before a strategy is set aside. */
export const DENIAL_AFTER = 2;
const POOL = 4;

export interface Who { id: Guid; imageUrl: string }

/** What a strategy's answer means for one person. `refused` is about the token (or the route), `none` about the person. */
export type Outcome = { kind: 'image'; dataUrl: string } | { kind: 'none' } | { kind: 'refused' } | { kind: 'error' };

interface Request { url: string; binary: boolean; version?: Version }
interface Strategy {
  id: StrategyId;
  /** The request for this person, or null when the strategy can't apply (no identity host, no descriptor). */
  request(org: string, who: Who): Request | null;
  decode(res: AdoResponse): Outcome;
}

const IMAGE_TYPE = /^image\/(png|jpeg|gif|webp|svg\+xml)$/;
const none: Outcome = { kind: 'none' };
const refused: Outcome = { kind: 'refused' };
const error: Outcome = { kind: 'error' };

/** The picture's type from its first bytes, for answers that carry no content type (Graph's base64). */
export function sniff(b: Uint8Array): string | null {
  if (b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47) return 'image/png';
  if (b[0] === 0xff && b[1] === 0xd8) return 'image/jpeg';
  if (b[0] === 0x47 && b[1] === 0x49 && b[2] === 0x46) return 'image/gif';
  if (b.length > 12 && b[0] === 0x52 && b[1] === 0x49 && b[2] === 0x46 && b[3] === 0x46 && b[8] === 0x57 && b[9] === 0x45 && b[10] === 0x42 && b[11] === 0x50) return 'image/webp';
  const head = Buffer.from(b.subarray(0, 64)).toString('utf8').trimStart();
  return head.startsWith('<svg') || (head.startsWith('<?xml') && head.includes('<svg')) ? 'image/svg+xml' : null;
}

const image = (type: string, bytes: Uint8Array): Outcome =>
  bytes.byteLength > MAX_BYTES ? none : { kind: 'image', dataUrl: `data:${type};base64,${Buffer.from(bytes).toString('base64')}` };

/** What the status alone says, or null for a 200 whose body the strategy must read. */
function byStatus(res: AdoResponse): Outcome | null {
  const s = res.status;
  if (s === 200) return null;
  if (s === 404 || s === 204) return none;
  if (s === 401 || s === 403 || s === 203 || (s >= 300 && s < 400)) return refused; // 3xx, 203: bounced to a sign-in page
  return error;
}

/** A body that is the picture itself. A 200 that isn't an image (a sign-in page) is the route refusing us. */
function decodeBinary(res: AdoResponse): Outcome {
  const early = byStatus(res);
  if (early) return early;
  const type = (res.headers['content-type'] ?? '').split(';')[0]!.trim();
  if (!(res.body instanceof Uint8Array)) return refused;
  return IMAGE_TYPE.test(type) ? image(type, res.body) : refused;
}

/** The Graph descriptor (`aad.…`) the identity's picture link names. */
export const descriptorOf = (imageUrl: string): string | null => {
  const m = /\/MemberAvatars\/([^/?#]+)/i.exec(imageUrl);
  try { return m ? decodeURIComponent(m[1]!) : null; } catch { return null; }
};

const STRATEGIES: Record<StrategyId, Strategy> = {
  // The identity's own link, as ADO wrote it into the work item.
  member: { id: 'member', request: (_org, who) => ({ url: who.imageUrl, binary: true }), decode: decodeBinary },
  // Graph - Avatars - Get (vso.graph): JSON with the picture in base64. ADO draws an initials picture when
  // there is none (`isAutoGenerated`); the chart draws its own initials, so that counts as no picture.
  graph: {
    id: 'graph',
    request: (org, who) => {
      const base = vsspsBaseOf(org);
      const d = descriptorOf(who.imageUrl);
      return base && d ? { url: `${base}/_apis/graph/Subjects/${encodeURIComponent(d)}/avatars?size=medium`, binary: false, version: '7.1-preview.1' } : null;
    },
    decode: (res) => {
      const early = byStatus(res);
      if (early) return early;
      const b = res.body as { value?: unknown; isAutoGenerated?: unknown } | null;
      if (!b || typeof b !== 'object') return refused;
      if (b.isAutoGenerated === true) return none;
      const bytes = typeof b.value === 'string' ? Buffer.from(b.value, 'base64') : Array.isArray(b.value) ? Uint8Array.from(b.value as number[]) : null;
      const type = bytes ? sniff(bytes) : null;
      return bytes && type ? image(type, bytes) : none;
    },
  },
  // The web app's identity image, by the identity's ID. Undocumented, so it goes last; it costs
  // nothing when the token can't use it, because a refusal sets it aside.
  web: {
    id: 'web',
    request: (org, who) => ({ url: `${org.replace(/\/+$/, '')}/_api/_common/identityImage?id=${who.id}&__v=5`, binary: true, version: null }),
    decode: decodeBinary,
  },
};

// ---- what an org has taught us ----

/** Kept per org in the cache's settings (not the picture bytes: those are on `identities`). */
interface Memory { preferred?: StrategyId; denied?: Partial<Record<StrategyId, number>> }
const memoryKey = (org: OrgKey) => `avatars:${org}`;

/** What `fetchPictures` needs of the cache. */
export interface PicturePort {
  setting<T>(key: string): T | null;
  setSetting(key: string, value: unknown): void;
  setAvatar(org: OrgKey, id: Guid, dataUrl: string | null): void;
  clearMissedAvatars(org: OrgKey): void;
}
/** What it needs of the ADO client. */
export interface PictureClient {
  org: string;
  avatarRaw(url: string, opts: { binary: boolean; version?: Version }): Promise<AdoResponse>;
}

/** A new token (or a new org's first) may be allowed what the old one wasn't: forget the refusals and ask again for the misses. */
export function resetPictureMemory(cache: PicturePort, org: OrgKey): void {
  const m = cache.setting<Memory>(memoryKey(org));
  if (m?.denied) cache.setSetting(memoryKey(org), { ...m, denied: {} });
  cache.clearMissedAvatars(org);
}

/** The strategies to try now, best first: what worked, then the defaults, without those set aside. */
export function strategyOrder(mem: Memory, now: number): StrategyId[] {
  const base = mem.preferred ? [mem.preferred, ...DEFAULT_ORDER.filter((s) => s !== mem.preferred)] : [...DEFAULT_ORDER];
  return base.filter((s) => { const at = mem.denied?.[s]; return at === undefined || at + DENIED_TTL_MS <= now; });
}

export interface PictureRun {
  client: PictureClient;
  cache: PicturePort;
  org: OrgKey;
  who: Who[];
  now: number;
  /** Throws when the user moved on (the sync's abort check). */
  checkAbort?: () => void;
}

/**
 * Fetch the pictures for these people, four at a time. A person gets the first picture any strategy
 * finds. "No picture" (a 404, or ADO's drawn initials) is believed from a route that hasn't been
 * refusing us; otherwise the other routes are asked. It is stored (`''`, asked once) only when a strategy said so: if every route was
 * refused or failed, the person stays unasked and a later sync tries again, at no cost while the
 * refusals stand.
 */
export async function fetchPictures(r: PictureRun): Promise<void> {
  if (!r.who.length) return;
  const mem: Memory = { ...(r.cache.setting<Memory>(memoryKey(r.org)) ?? {}) };
  mem.denied = { ...(mem.denied ?? {}) };
  const refusals: Partial<Record<StrategyId, number>> = {};
  const wins: Partial<Record<StrategyId, number>> = {};
  const tally: Record<StrategyId, { image: number; none: number; refused: number; error: number }> = {
    member: { image: 0, none: 0, refused: 0, error: 0 }, graph: { image: 0, none: 0, refused: 0, error: 0 }, web: { image: 0, none: 0, refused: 0, error: 0 },
  };
  let dirty = false;
  // A route's "no picture" is believed unless it has also been refusing us: a route that answers 404 and
  // never 401 can see people fine, so its 404 is about the person.
  const trusted = (s: StrategyId) => mem.preferred === s || (wins[s] ?? 0) > 0 || !refusals[s];

  const one = async (who: Who): Promise<void> => {
    let said = false; // some strategy answered "no picture for this person"
    for (const id of strategyOrder(mem, r.now)) {
      const s = STRATEGIES[id];
      const req = s.request(r.client.org, who);
      if (!req) continue;
      let out: Outcome;
      try {
        out = s.decode(await r.client.avatarRaw(req.url, req.version === undefined ? { binary: req.binary } : { binary: req.binary, version: req.version }));
      } catch (e) {
        if (!(e instanceof Error) || e.name === 'AbortError') throw e;
        out = error;
      }
      tally[id][out.kind]++;
      if (out.kind === 'image') {
        r.cache.setAvatar(r.org, who.id, out.dataUrl);
        wins[id] = (wins[id] ?? 0) + 1;
        if (mem.preferred !== id || mem.denied![id] !== undefined) { mem.preferred = id; delete mem.denied![id]; dirty = true; }
        return;
      }
      if (out.kind === 'none') {
        said = true;
        if (trusted(id)) break; // no need to ask the other routes
      } else if (out.kind === 'refused') {
        refusals[id] = (refusals[id] ?? 0) + 1;
        if (refusals[id]! >= DENIAL_AFTER && !wins[id]) {
          mem.denied![id] = r.now;
          dirty = true;
          devlog.write('main', 'avatar-denied', { via: id });
        }
      }
    }
    if (said) r.cache.setAvatar(r.org, who.id, null);
  };

  let next = 0;
  const worker = async () => {
    while (next < r.who.length) {
      const who = r.who[next++]!;
      r.checkAbort?.();
      await one(who);
    }
  };
  await Promise.all(Array.from({ length: Math.min(POOL, r.who.length) }, worker));

  if (dirty) r.cache.setSetting(memoryKey(r.org), mem);
  for (const id of DEFAULT_ORDER) {
    const t = tally[id];
    if (t.image + t.none + t.refused + t.error) devlog.write('main', 'avatar-fetch', { via: id, ...t });
  }
}
